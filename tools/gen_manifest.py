#!/usr/bin/env python3
"""Generate crates/setup/src/manifest_data.rs from work/setup-table.json.

Run from anywhere with `python3 -I tools/gen_manifest.py`. The input is a
JSON array of [relpath, size, setup_offset, sha256hex] rows. When the
extracted Setup.exe and installed files exist under work/, every row is
verified against them. The output only holds paths, sizes, offsets and
hashes.
"""

import hashlib
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLE = os.path.join(ROOT, "work", "setup-table.json")
SETUP = os.path.join(ROOT, "work", "iso", "Setup.exe")
APP = os.path.join(ROOT, "work", "game", "app")
OUT = os.path.join(ROOT, "crates", "setup", "src", "manifest_data.rs")

SETUP_SIZE = 341048406
SETUP_SHA256 = "b2124fa4f7dd31e5763580f4ae1c9a833ac0651d6cb3c40bce7ac8fd56fa077b"
EXPECTED_ROWS = 88


def sha256_file(path, offset=0, size=None):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        f.seek(offset)
        left = size
        while left is None or left > 0:
            n = 1 << 20 if left is None else min(1 << 20, left)
            chunk = f.read(n)
            if not chunk:
                break
            h.update(chunk)
            if left is not None:
                left -= len(chunk)
        if left:
            raise SystemExit(f"{path}: short read at {offset}")
    return h.hexdigest()


def rust_bytes(hexstr):
    b = bytes.fromhex(hexstr)
    if len(b) != 32:
        raise SystemExit(f"bad sha256 {hexstr}")
    return "[" + ", ".join(f"0x{x:02x}" for x in b) + "]"


def main():
    with open(TABLE, encoding="utf-8") as f:
        rows = json.load(f)
    entries = []
    for rel, size, off, sha in rows:
        path = rel.replace("\\", "/")
        if path.lower().startswith("app/"):
            path = path[4:]
        if not path or ".." in path.split("/") or '"' in path:
            raise SystemExit(f"bad path {rel!r}")
        entries.append((path, int(size), int(off), sha.lower()))
    if len(entries) != EXPECTED_ROWS:
        raise SystemExit(f"expected {EXPECTED_ROWS} rows, got {len(entries)}")
    entries.sort(key=lambda e: (e[2], e[0]))
    for a, b in zip(entries, entries[1:]):
        # Identical files share one payload; any other overlap is an error.
        if (a[1], a[2], a[3]) == (b[1], b[2], b[3]):
            continue
        if a[2] + a[1] > b[2]:
            raise SystemExit(f"overlapping ranges {a[0]} {b[0]}")
    if entries[-1][2] + entries[-1][1] > SETUP_SIZE:
        raise SystemExit("range past end of Setup.exe")

    have_setup = os.path.isfile(SETUP)
    if have_setup:
        if os.path.getsize(SETUP) != SETUP_SIZE:
            raise SystemExit("Setup.exe size mismatch")
        if sha256_file(SETUP) != SETUP_SHA256:
            raise SystemExit("Setup.exe sha256 mismatch")
        with open(SETUP, "rb") as f:
            for path, size, off, sha in entries:
                f.seek(off - 4)
                if f.read(4) != b"zlb\x1a":
                    raise SystemExit(f"{path}: no zlb marker before {off}")
    checked = 0
    for path, size, off, sha in entries:
        if have_setup and sha256_file(SETUP, off, size) != sha:
            raise SystemExit(f"{path}: Setup.exe range hash mismatch")
        src = os.path.join(APP, *path.split("/"))
        if os.path.isfile(src):
            if os.path.getsize(src) != size or sha256_file(src) != sha:
                raise SystemExit(f"{path}: installed file mismatch")
            checked += 1

    out = []
    out.append("// @generated by tools/gen_manifest.py from work/setup-table.json. Do not edit.")
    out.append("")
    out.append("use crate::manifest::{Manifest, ManifestEntry};")
    out.append("")
    out.append("/// Files installed by the TopCD release `Setup.exe`, sorted by offset.")
    out.append("/// Identical files may share one payload range.")
    out.append("pub static TOPCD: Manifest = Manifest {")
    out.append(f"    setup_size: {SETUP_SIZE},")
    out.append(f"    setup_sha256: {rust_bytes(SETUP_SHA256)},")
    out.append("    files: &[")
    for path, size, off, sha in entries:
        out.append("        ManifestEntry {")
        out.append(f'            path: "{path}",')
        out.append(f"            setup_offset: {off},")
        out.append(f"            size: {size},")
        out.append(f"            sha256: {rust_bytes(sha)},")
        out.append("        },")
    out.append("    ],")
    out.append("};")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(
        f"wrote {OUT}: {len(entries)} files, setup verified: {have_setup}, "
        f"installed files verified: {checked}",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
