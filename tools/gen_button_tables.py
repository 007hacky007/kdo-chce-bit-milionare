#!/usr/bin/env python3
"""Generate crates/engine/src/button_tables.rs from the button group tables.

Run from anywhere with `python3 -I tools/gen_button_tables.py`. The input is
`static_tables.button_tables` in analysis/evidence/milionar-static-tables.json
(numbers only: per button the overlay buffer address, position, hit rect, hotkey,
result id, initial state and the start/end frames of its four animations).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLES = os.path.join(ROOT, "analysis", "evidence", "milionar-static-tables.json")
OUT = os.path.join(ROOT, "crates", "engine", "src", "button_tables.rs")

ANIMS = ("normal", "hover", "pressed", "disabled")


def main():
    with open(TABLES, encoding="ascii") as f:
        tables = json.load(f)["static_tables"]["button_tables"]
    out = []
    w = out.append
    w("// @generated by tools/gen_button_tables.py from")
    w("// analysis/evidence/milionar-static-tables.json (`button_tables`). Do not edit.")
    w("//! Button group tables (F6.2): one array per group, buttons in exe order.")
    w("")
    w("use crate::buttons::ButtonDef;")
    for addr in sorted(tables, key=lambda a: int(a, 16)):
        buttons = tables[addr]
        w("")
        w("/// Button table %s." % addr)
        w("pub const TABLE_%06X: [ButtonDef; %d] = [" % (int(addr, 16), len(buttons)))
        for b in buttons:
            assert 0 <= b["key"] <= 0xFF and -1 <= b["id"] <= 0xFFFF, b["addr"]
            anims = ", ".join(
                "[%d, %d]" % tuple(b["anims_start_end"][a]) for a in ANIMS
            )
            w("    ButtonDef {")
            w("        smk: 0x%06x," % int(b["smk_struct"], 16))
            w("        x: %d," % b["x"])
            w("        y: %d," % b["y"])
            w("        rect: [%s]," % ", ".join(str(v) for v in b["rect"]))
            w("        key: %d," % b["key"])
            w("        id: %d," % b["id"])
            w("        state: %d," % b["state"])
            w("        anims: [%s]," % anims)
            w("    },")
        w("];")
    text = "\n".join(out) + "\n"
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d tables)" % (os.path.relpath(OUT, ROOT), len(tables)))


if __name__ == "__main__":
    main()
