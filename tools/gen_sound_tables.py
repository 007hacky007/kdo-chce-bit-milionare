#!/usr/bin/env python3
"""Generate crates/engine/src/sound_tables.rs from the SoundEvent pool tables.

Run from anywhere with `python3 -I tools/gen_sound_tables.py`. The input is
`sound_events` in analysis/evidence/milionar-static-tables.json (numbers only:
the initial order of every 25-slot pool, the pool arrays selected by an event
argument, and the weapon voice table). The output holds only those numbers.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLES = os.path.join(ROOT, "analysis", "evidence", "milionar-static-tables.json")
OUT = os.path.join(ROOT, "crates", "engine", "src", "sound_tables.rs")


def const_name(va):
    return "P_%06X" % va


def main():
    with open(TABLES, encoding="ascii") as f:
        se = json.load(f)["sound_events"]
    pools = sorted((int(k, 16), v) for k, v in se["pools"].items())
    for va, items in pools:
        assert 1 <= len(items) <= 25 and all(0 < x <= 0xFFFF for x in items), hex(va)
    arrays = sorted((int(k, 16), v) for k, v in se["pool_arrays"].items())
    weapon = se["weapon_voice_0x421e7c"]

    out = []
    w = out.append
    w("// @generated by tools/gen_sound_tables.py from")
    w("// analysis/evidence/milionar-static-tables.json (`sound_events`). Do not edit.")
    w("//! SoundEvent pool tables (F7.4): initial order of every pool as in the exe.")
    w("")
    w("/// Number of distinct pool structs.")
    w("pub const POOL_COUNT: usize = %d;" % len(pools))
    w("")
    w("/// Original address of each pool struct (diagnostics).")
    w("pub const POOL_VA: [u32; POOL_COUNT] = [")
    for va, _ in pools:
        w("    0x%06x," % va)
    w("];")
    w("")
    w("/// Initial items of each pool, in exe order.")
    w("pub const POOL_ITEMS: [&[u16]; POOL_COUNT] = [")
    for va, items in pools:
        w("    &[%s]," % ", ".join(str(x) for x in items))
    w("];")
    w("")
    for i, (va, _) in enumerate(pools):
        w("pub const %s: usize = %d;" % (const_name(va), i))
    w("")
    for va, arr in arrays:
        members = [const_name(int(m, 16)) for m in arr["members"]]
        w("/// Pool array 0x%06x, index: %s." % (va, arr["indexed_by"]))
        w("pub const PA_%06X: [usize; %d] = [%s];" % (va, len(members), ", ".join(members)))
    w("")
    w("/// CHAR id per weapon 0..14 (event 0x55, table 0x421e7c); 0 = no line.")
    w("pub const WEAPON_VOICE: [u16; %d] = [%s];" % (len(weapon), ", ".join(str(x) for x in weapon)))
    text = "\n".join(out) + "\n"
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d pools)" % (os.path.relpath(OUT, ROOT), len(pools)))


if __name__ == "__main__":
    main()
